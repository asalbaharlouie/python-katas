def find_max(MyList):
    max_num = MyList[0]
    # -------------------------------------------------------------------
# نکته مهم: مقایسه حلقه for و while در پیمایش لیست‌ها
# 
# ۱. حلقه for:
#    - انتخاب اول و استاندارد برای پیمایش لیست.
#    - مستقیماً اعضای لیست رو برمی‌گردونه و نیاز به مدیریت دستی اندیس (index) نداره.
#    - کد خواناتر، خلوت‌تر و کمتر دچار خطای انسانی (مثل حلقه بی‌نهایت) میشه.
#
# ۲. حلقه while:
#    - زمانی عالیه که تعداد تکرار مشخص نیست و وابسته به یک شرطه.
#    - اگر برای پیمایش لیست استفاده بشه، باید دستی یک متغیر اندیس (index=0)
#      تعریف کنیم و در هر دور اون رو دستی یکی اضافه کنیم (index += 1).
# -------------------------------------------------------------------
    for i in MyList:
        if i > max_num:
            max_num = i
    return max_num
        

def test_find_max():
    assert find_max([1, 5, 11]) == 11

test_find_max()

print(find_max([-3, -29, -0.5, -4]))